"""Table IV (deployment-facet comparison) marks from the metrics matrix.

Rule, as stated in the table caption: facets are pooled over both hardened
datasets (exp_h_adsys MNIST and femh_adsys FEMNIST: the per-method facet
value is the mean of the two dataset means from trustfl.metrics_matrix),
ranked per facet with ties sharing the higher mark; ranks 1-3 = filled
(CIRCLE, 2), 4-5 = half (LEFTcircle, 1), 6-7 = empty (Circle, 0).
Facets and direction: accuracy (final_acc, higher), retention (hm_retention,
higher), security (mal_infl, lower), delivery (deliv_eff, higher), energy
(energy_per_update, lower), cost (agg_ms, lower).

    python paper_assets/make_table4_marks.py --store <store> --out <dir>

Writes <out>/table4_rows.tex (LaTeX body rows), <out>/table4_marks.csv
(numeric marks 2/1/0 plus the pooled facet means) and
<out>/matrix_<prefix>.csv for each dataset (the raw metrics_matrix output).
"""
from __future__ import annotations

import argparse
import os

import pandas as pd

from trustfl.metrics_matrix import matrix
from trustfl.store import Store

PREFIXES = ["exp_h_adsys", "femh_adsys"]
FACETS = [("final_acc", "acc", False), ("hm_retention", "ret", False),
          ("mal_infl", "infl", True), ("deliv_eff", "deliv", False),
          ("energy_per_update", "energy", True), ("agg_ms", "cost", True)]
ORDER = ["TrustFL", "Sophon", "FedAA", "FLTrust", "FedGreed", "Multi-Krum", "FedAvg"]
TEX = {2: r"\CIRCLE", 1: r"\LEFTcircle", 0: r"\Circle"}
CITE = {"TrustFL": r"\textbf{TrustFL}", "Sophon": "Sophon", "FedAA": "FedAA",
        "FLTrust": "FLTrust", "FedGreed": "FedGreed", "Multi-Krum": "Multi-Krum",
        "FedAvg": "FedAvg"}


def mark(rank: float) -> int:
    if rank != rank:
        return -1
    return 2 if rank <= 3 else (1 if rank <= 5 else 0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--store", default="./results_store")
    ap.add_argument("--out", default="./paper_assets/tables")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    s = Store(a.store)
    mats = {}
    for p in PREFIXES:
        df = matrix(s, p)
        df.to_csv(os.path.join(a.out, f"matrix_{p}.csv"), index=False)
        mats[p] = df.set_index("method")
    pooled = pd.DataFrame({k: (mats[PREFIXES[0]][k] + mats[PREFIXES[1]][k]) / 2
                           for k, _, _ in FACETS})
    pooled = pooled.loc[[m for m in ORDER if m in pooled.index]]
    marks = pd.DataFrame(index=pooled.index)
    for k, short, lower in FACETS:
        rk = pooled[k].rank(ascending=lower, method="min")
        marks[short] = rk.map(mark)
        pooled[f"rank_{short}"] = rk
    out = pd.concat([marks, pooled], axis=1)
    out.index.name = "method"
    out.to_csv(os.path.join(a.out, "table4_marks.csv"))
    rows = ["% AUTO-GENERATED by paper_assets/make_table4_marks.py from the "
            "metrics matrix (pooled over exp_h_adsys + femh_adsys) -- never hand-edit.",
            "% facets: accuracy, retention, security(influence), delivery, energy, cost"]
    for m in marks.index:
        cells = " & ".join(TEX[int(v)] if v >= 0 else "--" for v in marks.loc[m])
        rows.append(f"{CITE[m]:12s} & {cells} \\\\")
    open(os.path.join(a.out, "table4_rows.tex"), "w").write("\n".join(rows) + "\n")
    print(out.round(4).to_string())
    print("\nmarks:", {m: [int(v) for v in marks.loc[m]] for m in marks.index})
    print(f"wrote {a.out}/table4_rows.tex, table4_marks.csv, matrix_*.csv")


if __name__ == "__main__":
    main()
